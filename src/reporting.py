"""
Markdown report of the evaluation results (results/evaluation_*.json, written by
scripts/evaluate.py), generated by scripts/report.py.

Two JSON formats exist: hold-out (one checkpoint, plain floats) and cross-validation
(--cv: {"mean", "std"} over the folds, plus "per_fold"). Older files lack some fields
(NSD, inference settings, post-processing): they are shown as "—".
"""

import json
from dataclasses import dataclass, field
from pathlib import Path

from src.data.transforms import ORGAN_NAMES


@dataclass
class EvaluationResult:
    """One evaluation file, normalized across the JSON formats."""

    name: str
    folds: int
    patients: int | None
    checkpoint_kind: str | None
    postprocess: bool
    inference: str | None
    dice: tuple[float, float | None]
    hd95: tuple[float, float | None]
    nsd: tuple[float, float | None] | None
    missed: int | None
    dice_per_organ: list[float | None] = field(default_factory=list)
    hd95_per_organ: list[float | None] = field(default_factory=list)
    nsd_per_organ: list[float | None] = field(default_factory=list)


def _stat(value) -> tuple[float, float | None] | None:
    """(mean, std) from a CV {"mean", "std"} dict or a hold-out float; std None if single run."""
    if value is None:
        return None
    if isinstance(value, dict):
        return float(value["mean"]), float(value["std"])
    return float(value), None


def _per_organ(value) -> list[float | None]:
    if value is None:
        return []
    return list(value["mean"]) if isinstance(value, dict) else list(value)


def _inference(settings: dict | None) -> str | None:
    if not settings:
        return None
    text = f"{settings['mode']} {round(settings['overlap'] * 100)} %"
    return text + " + TTA" if settings.get("tta") else text


def _missed(data: dict) -> int | None:
    """Organs present in the label but never predicted, summed over the volumes (and folds)."""
    if "missed_per_organ" in data:
        return int(sum(data["missed_per_organ"]))
    folds = data.get("per_fold") or []
    if folds and all("missed_per_organ" in f for f in folds):
        return int(sum(sum(f["missed_per_organ"]) for f in folds))
    return None


def parse_result(name: str, data: dict) -> EvaluationResult:
    """
    Args:
        name: Label of the result (file name without "evaluation_" and ".json").
        data: Content of the JSON file.

    Returns:
        The normalized result.
    """
    per_fold = data.get("per_fold")
    if per_fold:
        patients = sum(f.get("num_patients", 0) for f in per_fold) or None
    else:
        patients = data.get("num_patients")
    folds = len(data.get("folds") or [1])

    def stat(value) -> tuple[float, float | None] | None:
        parsed = _stat(value)
        # A single fold has no spread: the std of 0.0 written by evaluate.py is meaningless
        return (parsed[0], None) if parsed is not None and folds == 1 else parsed

    return EvaluationResult(
        name=name,
        folds=folds,
        patients=patients,
        checkpoint_kind=data.get("checkpoint_kind"),
        postprocess=bool(data.get("postprocess", False)),
        inference=_inference(data.get("inference")),
        dice=stat(data["mean_dice"]),
        hd95=stat(data["mean_hd95"]),
        nsd=stat(data.get("mean_nsd")),
        missed=_missed(data),
        dice_per_organ=_per_organ(data.get("dice_per_organ")),
        hd95_per_organ=_per_organ(data.get("hd95_per_organ")),
        nsd_per_organ=_per_organ(data.get("nsd_per_organ")),
    )


def load_results(results_dir: Path) -> list[EvaluationResult]:
    """All results/evaluation_*.json files, sorted by name."""
    results = []
    for path in sorted(results_dir.glob("evaluation*.json")):
        name = path.stem.removeprefix("evaluation_").removeprefix("evaluation") or "evaluation"
        results.append(parse_result(name, json.loads(path.read_text(encoding="utf-8"))))
    return results


def _fmt(stat: tuple[float, float | None] | None, spec: str) -> str:
    if stat is None:
        return "—"
    mean, std = stat
    return f"{mean:{spec}}" if std is None else f"{mean:{spec}} ± {std:{spec}}"


def _cell(value: float | None, spec: str) -> str:
    return "—" if value is None else f"{value:{spec}}"


def _summary_table(results: list[EvaluationResult]) -> list[str]:
    lines = [
        "| Résultat | Volumes | Checkpoint | Post-traitement | Inférence | Dice | HD95 (mm) | NSD | Organes manqués |",
        "| :--- | ---: | :--- | :--- | :--- | :--- | :--- | :--- | ---: |",
    ]
    for r in sorted(results, key=lambda r: -r.dice[0]):
        hd95 = _fmt(r.hd95, ".1f") + ("" if r.nsd is not None else " †")
        lines.append(
            f"| `{r.name}` | {r.patients or '—'} | {r.checkpoint_kind or '—'} | {'oui' if r.postprocess else 'non'} "
            f"| {r.inference or '—'} | {_fmt(r.dice, '.3f')} | {hd95} | {_fmt(r.nsd, '.3f')} "
            f"| {'—' if r.missed is None else r.missed} |"
        )
    return lines


def _organ_table(result: EvaluationResult) -> list[str]:
    lines = ["| Organe | Dice | HD95 (mm) | NSD |", "| :--- | ---: | ---: | ---: |"]
    for i, organ in enumerate(ORGAN_NAMES):
        dice, hd95, nsd = (values[i] if i < len(values) else None
                           for values in (result.dice_per_organ, result.hd95_per_organ, result.nsd_per_organ))
        lines.append(f"| {i + 1} {organ} | {_cell(dice, '.3f')} | {_cell(hd95, '.1f')} | {_cell(nsd, '.3f')} |")
    return lines


def render_report(results: list[EvaluationResult]) -> str:
    """
    Markdown report: one table for the cross-validation results, one for the single-fold /
    hold-out results (both sorted by Dice), and the per-organ scores of the best CV result.

    Args:
        results: Parsed evaluation files.

    Returns:
        The report, ending with a newline.
    """
    cv = [r for r in results if r.folds > 1]
    single = [r for r in results if r.folds == 1]
    lines = [
        "# Rapport d'évaluation",
        "",
        "Généré par `python scripts/report.py` depuis `results/evaluation_*.json` : ne pas modifier à la main.",
        "",
        "Moyenne sur les volumes de validation (± écart-type entre folds en validation croisée). "
        "† : évaluation antérieure à la convention actuelle (organe manqué compté HD95 = diagonale "
        "du volume, NSD = 0) ; son HD95 n'est pas comparable.",
        "",
    ]
    if cv:
        lines += ["## Validation croisée", "", *_summary_table(cv), ""]
    if single:
        lines += ["## Un seul fold ou hold-out", "", *_summary_table(single), ""]
    if cv:
        best = max(cv, key=lambda r: r.dice[0])
        lines += [f"## Par organe : `{best.name}` (meilleur Dice en validation croisée)", "",
                  *_organ_table(best), ""]
    return "\n".join(lines)
